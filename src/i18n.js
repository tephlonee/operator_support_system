const STORAGE_KEY = 'operator-picking.lang';
let lang = readSaved() || 'en';

function readSaved() {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    return STRINGS[v] ? v : null;
  } catch { return null; }
}

export const getLang = () => lang;

export function setLang(next) {
  lang = STRINGS[next] ? next : 'en';
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* the choice just isn't remembered */ }
}

// t('palletCount', { n: 8 }) → "8 parts"
export function t(key, params = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '');
}

// Fill every element that has data-i18n="key" with its text in the current language.
export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach(node => { node.setAttribute('aria-label', t(node.dataset.i18nAria)); });
}

// 3000 → "3,000" in English, "3 000" in Swedish.
export const formatNumber = n => Number(n).toLocaleString(lang === 'sv' ? 'sv-SE' : 'en-GB');
